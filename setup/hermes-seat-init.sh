#!/usr/bin/env bash
# One-time seed of the ZTORCH hermes seat: an isolated HERMES_HOME whose config
# points at the box's Z.ai gateway, mounts the vault skills/ tree as hermes
# external skills, wires the qmd wiki-search MCP, and disables the curator.
# Idempotent: an existing config.yaml is left alone unless --force.
# Usage: bash setup/hermes-seat-init.sh [--force]
#   ZTORCH_HERMES_HOME   seat home (default ~/.hermes-ztorch)
#   ZTORCH_HERMES_BASE_URL  gateway base URL (default $ANTHROPIC_BASE_URL)
#   ZTORCH_HERMES_KEY    API key written to the seat .env (default $ANTHROPIC_AUTH_TOKEN)
#   ZTORCH_HERMES_VAULT  vault root (default: self-located)
set -uo pipefail
FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

VAULT="${ZTORCH_HERMES_VAULT:-$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)}"
[ -d "$VAULT/skills" ] || { echo "vault root not resolved: $VAULT (set ZTORCH_HERMES_VAULT)" >&2; exit 1; }

HOME_DIR="${ZTORCH_HERMES_HOME:-$HOME/.hermes-ztorch}"
BASE_URL="${ZTORCH_HERMES_BASE_URL:-${ANTHROPIC_BASE_URL:-}}"
KEY="${ZTORCH_HERMES_KEY:-${ANTHROPIC_AUTH_TOKEN:-}}"

mkdir -p "$HOME_DIR"
if [ -f "$HOME_DIR/config.yaml" ] && [ "$FORCE" -ne 1 ]; then
  echo "config.yaml exists at $HOME_DIR (unchanged); rerun with --force to regenerate"
else
  [ -n "$BASE_URL" ] || { echo "no base URL: set ZTORCH_HERMES_BASE_URL or ANTHROPIC_BASE_URL" >&2; exit 1; }
  cat > "$HOME_DIR/config.yaml" << EOF
# ZTORCH hermes seat (generated by setup/hermes-seat-init.sh; safe to edit by hand).
# Tier aliases mirror the brain tier table: haiku=glm-5.3-flash, sonnet=glm-5.3, opus=glm-5.3-max.
model:
  provider: ztorch-gw
  default: "glm-5.3-flash"
providers:
  ztorch-gw:
    base_url: "$BASE_URL"
    api_mode: anthropic_messages
    key_env: ZTORCH_HERMES_KEY
model_aliases:
  haiku:
    model: "glm-5.3-flash"
    provider: ztorch-gw
  sonnet:
    model: "glm-5.3"
    provider: ztorch-gw
  opus:
    model: "glm-5.3"  # glm-5.3-max absent on this gateway wire (Z.ai rejects it); best available
    provider: ztorch-gw
skills:
  external_dirs:
    - "$VAULT/skills"
mcp_servers:
  wiki-search:
    command: qmd
    args: ["mcp"]
    env:
      QMD_VAULT: "$VAULT"
curator:
  enabled: false
terminal:
  backend: local
EOF
  echo "wrote $HOME_DIR/config.yaml"
fi

# seed the key only when absent (never overwrite a hand-set key)
if [ -n "$KEY" ] && ! grep -q '^ZTORCH_HERMES_KEY=' "$HOME_DIR/.env" 2>/dev/null; then
  printf 'ZTORCH_HERMES_KEY=%s\n' "$KEY" >> "$HOME_DIR/.env"
  chmod 600 "$HOME_DIR/.env"
  echo "wrote ZTORCH_HERMES_KEY to $HOME_DIR/.env"
fi
[ -f "$HOME_DIR/.env" ] && grep -q '^ZTORCH_HERMES_KEY=' "$HOME_DIR/.env" \
  || echo "WARNING: no ZTORCH_HERMES_KEY in $HOME_DIR/.env (set it or export ANTHROPIC_AUTH_TOKEN and rerun)" >&2

echo "seat home: $HOME_DIR"
echo "next: bash scripts/hermes.sh check   &&   bash scripts/hermes.sh 'Reply with the single word OK'"
